class TestFractionalFactorialAliasStructure:
    
    """Test alias structure detection"""
    
    def test_alias_check_requires_model_matrix(self):
        """Test that alias_check requires model matrix to be computed first"""
        factors = {
            'X1': ContinuousFactor(n_levels=2, lower_bound=0, upper_bound=10, decimals=1),
            'X2': ContinuousFactor(n_levels=2, lower_bound=0, upper_bound=10, decimals=1),
            'X3': ContinuousFactor(n_levels=2, lower_bound=0, upper_bound=10, decimals=1)
        }
        
        design = FractionalFactorialDesign(factors=factors, resolution=3)
        
        # Should raise error if no model matrix exists
        with pytest.raises(ValueError, match="No model matrix defined"):
            design.alias_check()
    
    "Check that RES III design has no main effect aliasing"
    
    @pytest.mark.parametrize("num_factors", [4, 5, 6, 7, 8])
    def test_no_main_effect_aliasing_resolution_3(self, num_factors):
        
        """Test that Resolution III designs have no main effect aliasing"""
        
        factors = {f"X{i}": ContinuousFactor(n_levels=2, lower_bound=0, upper_bound=10, decimals=1)
                        for i in range(num_factors)}
        
        design = FractionalFactorialDesign(factors=factors, resolution=3)
        coded = design._coded_design_matrix
        tol = 1e-8
        # Check orthogonality between first num_factors columns (real factors)
        for i in range(num_factors):
            for j in range(i + 1, num_factors):
                dot_product = np.dot(coded.iloc[:, i].values, coded.iloc[:, j].values)
                assert abs(dot_product) <= 0 + tol, f"Factors {i} and {j} not orthogonal: dot={dot_product}"

    "Check that RES IV design has no main effect or 2-factor interaction aliasing"
    
    @pytest.mark.parametrize("num_factors, num_int2", [(4, 2), (5, 5), (6, 5), (7, 5), (8, 5)])
    def test_no_main_effect_2fi_aliasing_resolution_4(self, num_factors, num_int2):
        """Test that Resolution IV designs have no main effect or 2-factor interaction aliasing"""
        
        factors = {f"X{i}": ContinuousFactor(n_levels=2, lower_bound=0, upper_bound=10, decimals=1)
                        for i in range(num_factors)}
        
        design = FractionalFactorialDesign(factors=factors, resolution=4)
        coded = design._coded_design_matrix
        int2 = list(itertools.combinations(coded.columns, 2))[:num_int2] # Get the first num_int2 factor interactions
        model_terms = ModelTerms(intercept=True, pro_main="all", pro_int2=int2, pro_quadratic=None)
        design.set_model_terms(model_terms)
        tol = 1e-8
        
        # Check orthogonality between first num_factors columns - Main effects
        for i in range(num_factors):
            for j in range(i + 1, num_factors):
                dot_product = np.dot(coded.iloc[:, i].values, coded.iloc[:, j].values)
                assert abs(dot_product) <= 0 + tol, f"Factors {i} and {j} not orthogonal: dot={dot_product}"
        
        # Extract 2-factor interactions (columns after intercept and main effects)
        # Model matrix structure: [intercept, main_effects, 2FI]
        # Skip first (1 + num_factors) columns to get 2FI
        two_factor_interactions = design._model_matrix.iloc[:, (1 + num_factors):]
        
        # Check orthogonality between main effects and 2-factor interactions
        for i in range(num_factors):
            for j in range(two_factor_interactions.shape[1]):
                dot_product = np.dot(coded.iloc[:, i].values, two_factor_interactions.iloc[:, j].values)
                assert abs(dot_product) <= 0 + tol, f"Main effect {i} and 2-FI {j} not orthogonal: dot={dot_product}"

    "Check that RES V design has no 2-factor interaction aliasing with other 2-factor interactions"
    @pytest.mark.parametrize("num_factors", [5, 6, 7, 8])
    def test_no_2fi_2fi_aliasing_resolution_5(self, num_factors):
        """Test that Resolution V designs have no 2FI-2FI aliasing"""
        
        factors = {f"X{i}": ContinuousFactor(n_levels=2, lower_bound=0, upper_bound=10, decimals=1)
                        for i in range(num_factors)}
        
        design = FractionalFactorialDesign(factors=factors, resolution=5)
        model_terms = ModelTerms(intercept=True, pro_main="all", pro_int2="all", pro_quadratic=None)
        design.set_model_terms(model_terms)
        tol = 1e-8
        
        # Extract 2-factor interactions (columns after intercept and main effects)
        # Model matrix structure: [intercept, main_effects, 2FI]
        two_factor_interactions = design._model_matrix.iloc[:, (1 + num_factors):]
        
        # Check orthogonality between all pairs of 2-factor interactions
        for i in range(two_factor_interactions.shape[1]):
            for j in range(i + 1, two_factor_interactions.shape[1]):
                dot_product = np.dot(two_factor_interactions.iloc[:, i].values, 
                                   two_factor_interactions.iloc[:, j].values)
                assert abs(dot_product) <= 0 + tol, \
                    f"2-FI {i} and 2-FI {j} not orthogonal: dot={dot_product}"
                        
