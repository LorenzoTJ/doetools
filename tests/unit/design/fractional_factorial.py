class TestFractionalFactorialResolutionDifferences:
    """Test differences between resolution levels"""
    
    @pytest.mark.parametrize("num_factors", [4, 5, 6, 7, 8])
    def test_resolution_3_vs_4_run_counts(self, num_factors):
        """Test that Resolution III uses fewer runs than Resolution IV for same factors"""
        factors = {
            f'X{i}': ContinuousFactor(n_levels=2, lower_bound=0, upper_bound=10, decimals=1)
            for i in range(1, num_factors + 1)  
        }
        
        design_res3 = FractionalFactorialDesign(factors=factors, resolution=3)
        design_res4 = FractionalFactorialDesign(factors=factors, resolution=4)
        
        # Higher resolution needs more runs
        # Resolution III: more aggressive fraction
        # Resolution IV: less aggressive fraction (needs more runs)
        assert len(design_res4._coded_design_matrix) >= len(design_res3._coded_design_matrix)
    
    def test_resolution_affects_fraction_size(self):
        """Test that resolution controls the degree of fractionation"""
        factors = {
            f'X{i}': ContinuousFactor(n_levels=2, lower_bound=0, upper_bound=10, decimals=1)
            for i in range(1, 6)  # 5 factors
        }
        
        design_res3 = FractionalFactorialDesign(factors=factors, resolution=3)
        design_res5 = FractionalFactorialDesign(factors=factors, resolution=5)
        
        # Resolution V should use more runs (less fractionation)
        assert len(design_res5._coded_design_matrix) >= len(design_res3._coded_design_matrix)
        
        # Both should be less than full factorial (2^5 = 32)
        assert len(design_res3._coded_design_matrix) <= 32
        assert len(design_res5._coded_design_matrix) <= 32
    
class TestAliasStructureCheck:
    """Test alias structure checking functionality"""
    
    def test_alias_structure_detection_no_alias(self):
        """Test that no aliases are detected in well-designed Resolution IV design"""
        factors = {
            'A': ContinuousFactor(n_levels=2, lower_bound=0, upper_bound=10, decimals=1),
            'B': ContinuousFactor(n_levels=2, lower_bound=0, upper_bound=10, decimals=1),
            'C': ContinuousFactor(n_levels=2, lower_bound=0, upper_bound=10, decimals=1),
            'D': ContinuousFactor(n_levels=2, lower_bound=0, upper_bound=10, decimals=1)
        }
        
        design = FractionalFactorialDesign(factors=factors, resolution=4)
        int2 = list(itertools.combinations(factors.keys(), 2))[:3]  # First 3 two-factor interactions
        model_terms = ModelTerms(intercept=True, pro_main="all", pro_int2=int2, pro_quadratic=None)
        design.set_model_terms(model_terms)
        
        design.alias_check()
        
        # In a 2^(4-1) Resolution IV design, main effects should not be aliased with 2FI
        assert len(design._aliases) == 0
    
    def test_alias_structure_detection_alias(self):
        """Test that aliases are detected in Resolution III design with 2FI"""
        factors = {
            'A': ContinuousFactor(n_levels=2, lower_bound=0, upper_bound=10, decimals=1),
            'B': ContinuousFactor(n_levels=2, lower_bound=0, upper_bound=10, decimals=1),
            'C': ContinuousFactor(n_levels=2, lower_bound=0, upper_bound=10, decimals=1),
            'D': ContinuousFactor(n_levels=2, lower_bound=0, upper_bound=10, decimals=1),
            'E': ContinuousFactor(n_levels=2, lower_bound=0, upper_bound=10, decimals=1)
        }
        
        # 2^(5-2) Resolution III design: 8 runs, 5 factors
        design = FractionalFactorialDesign(factors=factors, resolution=3)
        
        # Test each 2FI individually to see which ones are aliased
        all_2fi = list(itertools.combinations(factors.keys(), 2))
        aliases_found = False
        
        for int2 in all_2fi:
            # Test with just main effects and this one 2FI
            # Model: 1 intercept + 5 main + 1 2FI = 7 terms (< 8 runs, not saturated)
            model_terms = ModelTerms(intercept=True, pro_main="all", pro_int2=[int2], pro_quadratic=None)
            design.set_model_terms(model_terms)
            design.alias_check()
            
            if len(design._aliases) > 0:
                aliases_found = True
                break
        
        # In Resolution III, at least some 2FI must be aliased with main effects
        assert aliases_found, "No aliases detected in Resolution III design with 2FI"
    
