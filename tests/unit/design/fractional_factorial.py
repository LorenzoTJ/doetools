"""
Comprehensive tests for Fractional Factorial Design.

Testing Strategy for Fractional Factorial:
-----------------------------------------
Unlike Full Factorial where we can verify exact matrices, Fractional Factorial
designs are generated by the doe_box library with specific mathematical properties.
We test PROPERTIES, not exact values:

1. Run count formula: 2^(k-p) where k=factors, p=fraction
2. All coded values must be -1 or +1 (2-level design)
3. Resolution properties (what's aliased and what's not)
4. Orthogonality of main effects
5. Balance (equal -1 and +1 counts per factor)
6. Fraction reduction (fewer runs than full factorial)
"""

import itertools
import numpy as np
import pytest
from doetools.design.process import FractionalFactorialDesign
from doetools.utils import ContinuousFactor
from doetools import ModelTerms


